"""Import Slicer's volume properties without hand-editing transfer-function data.

Usage: python scripts/import_slicer_presets.py path/to/presets.xml
The source XML and generated TypeScript are both retained for offline parity tests.
"""

import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE_URL = "https://raw.githubusercontent.com/Slicer/Slicer/main/Modules/Loadable/VolumeRendering/Resources/presets.xml"


def knots(text, width):
    values = [float(value) for value in text.split()]
    count = int(values.pop(0))
    if count != len(values) or count % width:
        raise ValueError("Invalid transfer-function control-point count")
    result = [values[index : index + width] for index in range(0, count, width)]
    if not result or any(a[0] > b[0] for a, b in zip(result, result[1:])):
        raise ValueError("Transfer-function control points are not ordered")
    return result


def main():
    source = Path(sys.argv[1]).read_bytes()
    presets = {}
    for node in ET.fromstring(source).findall("VolumeProperty"):
        attrs = node.attrib
        opacity = knots(attrs["scalarOpacity"], 2)
        color = knots(attrs["colorTransfer"], 4)
        gradient = knots(attrs["gradientOpacity"], 2)
        interpolation = {"0": "nearest", "1": "linear"}[attrs["interpolation"]]
        # effectiveRange is only an editor hint and includes invalid legacy
        # values upstream. Actual LUT bounds must cover every native knot.
        presets[attrs["name"]] = {
            "opacity": opacity,
            "color": color,
            "gradientOpacity": gradient,
            "shade": attrs["shade"] == "1",
            "interpolation": interpolation,
            **{key: float(attrs[key]) for key in ("ambient", "diffuse", "specular", "specularPower")},
            "transferRange": [min(opacity[0][0], color[0][0]), max(opacity[-1][0], color[-1][0])],
        }
    if not presets:
        raise ValueError("No volume presets found")
    target = ROOT / "web/src/lib/slicer-volume-presets.generated.ts"
    fixture = ROOT / "web/tests/fixtures/slicer-presets.xml"
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_bytes(source)
    header = (
        "/** Generated by scripts/import_slicer_presets.py; do not edit transfer data.\n"
        " * Copyright and redistribution terms: /licenses/Slicer-LICENSE.txt.\n"
        f" * Source: {SOURCE_URL}\n */\n"
        f"export const SLICER_PRESET_SOURCE_URL = {json.dumps(SOURCE_URL)};\n"
        f"export const SLICER_PRESET_SOURCE_SHA256 = {json.dumps(hashlib.sha256(source).hexdigest())};\n"
    )
    target.write_text(header + "export const SLICER_VOLUME_PRESET_DATA = " + json.dumps(presets, indent=2) + " as const;\n")
    print(f"Imported {len(presets)} Slicer presets into {target}")


if __name__ == "__main__":
    main()
