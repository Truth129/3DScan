"""Identity-preserving, overlap-aware Slicer segmentation interchange."""

from __future__ import annotations

from pathlib import Path
from itertools import product
import hashlib
import json
import tempfile
import zipfile

import nibabel as nib
import nrrd
import numpy as np
from scipy import ndimage as ndi

from .imaging import _binary, _foreground_bounds, _image, _save_mask, _world


def _color(value):
    value = str(value).lstrip("#")
    if len(value) != 6:
        raise ValueError("Invalid segment color")
    return [int(value[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def _reference_digest(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def export_bundle(ct_path: Path, structures, output_zip: Path) -> Path:
    ct, affine = _image(ct_path)
    output_zip = Path(output_zip)
    output_zip.parent.mkdir(parents=True, exist_ok=True)
    if not structures:
        raise ValueError("No structures to export")
    if len(structures) > 65535 or len({s["id"] for s in structures}) != len(structures):
        raise ValueError("Segmentation requires unique structure identities and at most 65535 labels")
    source_hash = _reference_digest(ct_path)
    # Greedily pack non-overlapping masks into layers. This preserves overlaps
    # across tasks while avoiding one full CT-sized layer per anatomical object.
    layers = []
    placement = []
    for index, structure in enumerate(structures):
        mask, _, _ = _binary(Path(structure["mask_file"]), ct, affine)
        layer_index = next((i for i, layer in enumerate(layers) if not np.any(layer[mask])), None)
        if layer_index is None:
            layer_index = len(layers)
            layers.append(np.zeros(ct.shape, dtype=np.uint16))
        label = index + 1
        layers[layer_index][mask] = label
        placement.append((layer_index, label, _foreground_bounds(mask)))
    # NRRD directions are one vector per array axis. Slicer convention is LPS.
    ras_to_lps = np.diag([-1.0, -1.0, 1.0])
    directions = (ras_to_lps @ affine[:3, :3]).T
    origin = ras_to_lps @ affine[:3, 3]
    header = {
        "space": "left-posterior-superior", "space directions": np.vstack((np.full(3, np.nan), directions)),
        "space origin": origin, "space units": ["mm", "mm", "mm"],
        "kinds": ["list", "domain", "domain", "domain"], "encoding": "gzip",
        "Segmentation_ContainedRepresentationNames": "Binary labelmap|",
        "Segmentation_MasterRepresentation": "Binary labelmap",
        "Segmentation_SourceRepresentation": "Binary labelmap",
        "Segmentation_ReferenceImageExtentOffset": "0 0 0",
        "Scan3D_SchemaVersion": "1",
        "Scan3D_ReferenceSHA256": source_hash,
    }
    for index, (structure, (layer, label, box)) in enumerate(zip(structures, placement)):
        prefix = f"Segment{index}_"
        low, high = box if box is not None else (np.zeros(3, dtype=int), np.full(3, -1, dtype=int))
        header.update({prefix + "ID": str(structure["id"]),
                       prefix + "Name": str(structure["name"]).replace("\n", " "),
                       prefix + "Color": " ".join(map(str, _color(structure.get("color", "#b7c4d0")))),
                       prefix + "NameAutoGenerated": "0", prefix + "ColorAutoGenerated": "0",
                       prefix + "Layer": str(layer), prefix + "LabelValue": str(label),
                       prefix + "Extent": " ".join(str(x) for pair in zip(low, high) for x in pair),
                       prefix + "Tags": (f"Scan3D.StructureID:{structure['id']}|"
                                         f"Scan3D.ReferenceSHA256:{source_hash}|")})
    with tempfile.TemporaryDirectory(prefix=".slicer-", dir=output_zip.parent) as temp:
        staging = Path(temp)
        # Reconstruct a minimal NIfTI header so portable bundles do not carry
        # free-text acquisition/patient fields from a source NIfTI header.
        reference = nib.Nifti1Image(np.asanyarray(ct.dataobj), affine)
        reference.header.set_xyzt_units("mm")
        reference.set_sform(affine, code=1)
        reference.set_qform(affine, code=1)
        nib.save(reference, str(staging / "reference.nii.gz"))
        data = np.stack(layers, axis=0)
        nrrd.write(str(staging / "segmentation.seg.nrrd"), data, header, index_order="F")
        mapping = {"schema_version": 1, "coordinates": "RAS millimetres",
                   "structures": [{key: structure[key] for key in ("id", "name", "task", "group", "color")
                                   if key in structure} for structure in structures]}
        (staging / "mapping.json").write_text(json.dumps(mapping, indent=2) + "\n")
        pending = staging / "bundle.zip"
        with zipfile.ZipFile(pending, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=1) as archive:
            for name in ("reference.nii.gz", "segmentation.seg.nrrd", "mapping.json"):
                archive.write(staging / name, name)
        pending.replace(output_zip)
    return output_zip


def _nrrd_geometry(header, ndim):
    space = str(header.get("space", "")).lower()
    if space in {"left-posterior-superior", "lps"}:
        to_ras = np.diag([-1.0, -1.0, 1.0])
    elif space in {"right-anterior-superior", "ras"}:
        to_ras = np.eye(3)
    else:
        raise ValueError("Corrected segmentation must use patient RAS or LPS coordinates")
    try:
        directions = np.asarray(header["space directions"], dtype=float)
        origin = np.asarray(header["space origin"], dtype=float)
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError("Corrected segmentation is missing patient geometry") from exc
    if directions.shape != (ndim, 3) or origin.shape != (3,) or not np.isfinite(origin).all():
        raise ValueError("Invalid segmentation direction/origin metadata")
    spatial_axes = [i for i, direction in enumerate(directions) if np.isfinite(direction).all()]
    list_axes = [i for i in range(ndim) if i not in spatial_axes]
    if len(spatial_axes) != 3 or len(list_axes) != ndim - 3:
        raise ValueError("Corrected segmentation must have exactly three spatial axes")
    factors = []
    for unit in header.get("space units", ["mm"] * 3):
        key = str(unit).strip('"').lower()
        factor = {"mm": 1, "millimeter": 1, "millimetre": 1, "m": 1000,
                  "meter": 1000, "metre": 1000, "um": 0.001, "micron": 0.001}.get(key)
        if factor is None:
            raise ValueError("Unsupported segmentation spatial units")
        factors.append(factor)
    if len(factors) != 3:
        raise ValueError("Invalid segmentation spatial units")
    to_ras = to_ras @ np.diag(factors)
    affine = np.eye(4)
    affine[:3, :3] = to_ras @ directions[spatial_axes].T
    affine[:3, 3] = to_ras @ origin
    if not np.isfinite(affine).all() or abs(np.linalg.det(affine[:3, :3])) < 1e-9:
        raise ValueError("Corrected segmentation has an invalid physical transform")
    return affine, spatial_axes, list_axes


def _aligned(mask, source_affine, ct_shape, ct_affine):
    transform = np.linalg.inv(ct_affine) @ source_affine
    linear = transform[:3, :3]
    rounded = np.rint(linear)
    # A cropped/reoriented labelmap retains the same voxel lattice. Reject a
    # different sampling lattice instead of quietly interpolating a correction.
    if (not np.allclose(linear, rounded, atol=1e-4, rtol=0)
            or not np.array_equal(np.abs(rounded).sum(axis=0), np.ones(3))
            or not np.array_equal(np.abs(rounded).sum(axis=1), np.ones(3))
            or not np.allclose(transform[:3, 3], np.rint(transform[:3, 3]), atol=1e-3, rtol=0)):
        raise ValueError("Corrected segmentation uses a different voxel grid; export it using the reference CT geometry")
    # Eliminate sub-voxel floating-point roundoff at cropped image boundaries.
    transform[:3, :3] = rounded
    transform[:3, 3] = np.rint(transform[:3, 3])
    box = _foreground_bounds(mask)
    if box is not None:
        corners = np.asarray(list(product(*zip(*box))), dtype=float)
        target = _world(transform, corners)
        if np.any(target.min(axis=0) < -1e-3) or np.any(target.max(axis=0) > np.asarray(ct_shape) - 1 + 1e-3):
            raise ValueError("Corrected foreground extends outside the reference CT")
    inverse = np.linalg.inv(transform)
    return ndi.affine_transform(mask.astype(np.uint8), inverse[:3, :3], inverse[:3, 3],
                                output_shape=ct_shape, order=0, mode="constant", cval=0,
                                prefilter=False).astype(bool)


def import_segmentation(ct_path: Path, seg_path: Path, structures, output_dir: Path,
                        require_source_hash: bool = False) -> list[dict]:
    ct, ct_affine = _image(ct_path)
    preview = nrrd.read_header(str(seg_path))
    if "data file" in preview or "datafile" in preview:
        raise ValueError("Detached NRRD data files are unsupported; upload a self-contained .seg.nrrd")
    source_hash = None
    if preview.get("Scan3D_ReferenceSHA256"):
        source_hash = _reference_digest(ct_path)
        if preview["Scan3D_ReferenceSHA256"] != source_hash:
            raise ValueError("This correction belongs to a different reference CT; use the original bundle from the selected case")
    global_identity = bool(preview.get("Scan3D_ReferenceSHA256"))
    sizes = np.asarray(preview.get("sizes", []), dtype=np.int64)
    if sizes.shape not in {(3,), (4,)} or np.any(sizes < 1):
        raise ValueError("Corrected segmentation has invalid array dimensions")
    # Bound expansion before decoding gzip or allocating a declared labelmap.
    # Eight bytes per voxel is conservative for all accepted integer NRRD types.
    count = 1
    for size in sizes:
        count *= int(size)
    if count * 8 > 8 * 1024 ** 3 or count > np.prod(ct.shape) * max(1, len(structures)):
        raise ValueError("Corrected segmentation exceeds the supported expanded image size")
    _nrrd_geometry(preview, len(sizes))
    data, header = nrrd.read(str(seg_path), index_order="F")
    if data.ndim not in {3, 4} or data.dtype.kind not in "uib":
        raise ValueError("Corrected segmentation must be a three- or four-dimensional integer labelmap")
    if data.dtype.kind == "i" and np.any(data < 0):
        raise ValueError("Corrected segmentation contains negative label values")
    affine, spatial, list_axes = _nrrd_geometry(header, data.ndim)
    if list_axes:
        data = np.transpose(data, list_axes + spatial)
    else:
        data = np.transpose(data, spatial)[None, ...]
    known = {str(structure["id"]): structure for structure in structures}
    corrected = {}
    used_label_values = set()
    index = 0
    while f"Segment{index}_ID" in header:
        prefix = f"Segment{index}_"
        stable_id = str(header[prefix + "ID"])
        # IDs from an exported bundle survive Slicer editing. The explicit tag
        # additionally survives workflows that reassign the MRML segment ID.
        tags = str(header.get(prefix + "Tags", ""))
        tagged_id = None
        tagged_hash = None
        for tag in tags.split("|"):
            if tag.startswith("Scan3D.StructureID:"):
                value = tag.split(":", 1)[1]
                if tagged_id is not None and tagged_id != value:
                    raise ValueError("Segment contains conflicting structure identity tags")
                tagged_id = value
            if tag.startswith("Scan3D.ReferenceSHA256:"):
                value = tag.split(":", 1)[1]
                if tagged_hash is not None and tagged_hash != value:
                    raise ValueError("Segment contains conflicting source CT identity tags")
                tagged_hash = value
        if tagged_id is not None:
            if stable_id in known and tagged_id != stable_id:
                raise ValueError("Segment ID conflicts with its preserved structure identity tag")
            stable_id = tagged_id
        if tagged_hash is not None:
            source_hash = source_hash or _reference_digest(ct_path)
            if tagged_hash != source_hash:
                raise ValueError("This correction belongs to a different reference CT; use the original bundle from the selected case")
        if require_source_hash and not (global_identity or tagged_hash is not None):
            raise ValueError("Correction lacks the source CT identity; edit and export the original Slicer bundle from this case")
        if stable_id not in known:
            raise ValueError("Corrected segmentation includes an unknown structure identity; use the exported bundle")
        if stable_id in corrected:
            raise ValueError("Corrected segmentation includes duplicate structure identities")
        try:
            layer = int(header.get(prefix + "Layer", 0))
            label = int(header[prefix + "LabelValue"])
        except (KeyError, ValueError) as exc:
            raise ValueError("Missing segment layer or label identity") from exc
        if layer < 0 or layer >= len(data) or label <= 0:
            raise ValueError("Invalid segment layer or label value")
        if (layer, label) in used_label_values:
            raise ValueError("Two structures share the same segment layer and label identity")
        used_label_values.add((layer, label))
        source = data[layer] == label
        # space origin already includes Slicer's crop. Applying the optional
        # ReferenceImageExtentOffset a second time would shift the anatomy.
        corrected[stable_id] = _aligned(source, affine, ct.shape, ct_affine)
        index += 1
    if not corrected:
        raise ValueError("No identified Slicer segments were found")
    declared = {(int(header.get(f"Segment{i}_Layer", 0)), int(header[f"Segment{i}_LabelValue"]))
                for i in range(index)}
    for layer_index, layer in enumerate(data):
        if any((layer_index, int(label)) not in declared for label in np.unique(layer) if label):
            raise ValueError("Corrected labelmap contains voxels without a segment identity")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    result = []
    for structure in structures:
        entry = dict(structure)
        stable_id = str(structure["id"])
        if stable_id in corrected:
            name = hashlib.sha256(stable_id.encode()).hexdigest()[:20] + ".nii.gz"
            path = output_dir / name
            if path.resolve() == Path(structure["mask_file"]).resolve():
                raise ValueError("A corrected mask must be written to a new revision")
            _save_mask(corrected[stable_id], ct, path)
            entry["mask_file"] = str(path.resolve())
        result.append(entry)
    return result
